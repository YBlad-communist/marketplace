-- Частичный уникальный индекс: не более одного АКТИВНОГО заказа на объявление.
-- Завершённые заказы (RELEASED/REFUNDED) индекс не покрывает — после возврата
-- объявление снова может получить новый заказ.
--
-- В schema.prisma индекс намеренно НЕ объявлен: Prisma не видит индексы с
-- WHERE-предикатом, и любая декларация (@@unique/@@index) дала бы drift —
-- следующий migrate dev сгенерировал бы CREATE уже существующего индекса
-- (или DROP частичного). Prisma при этом слеп и к самому индексу, поэтому
-- молча не трогает его при будущих миграциях.
--
-- Вынесен в отдельную миграцию от ADD VALUE: PostgreSQL запрещает
-- использовать новое значение enum в той же транзакции, где оно добавлено.
CREATE UNIQUE INDEX "Order_listingId_active_key" ON "Order"("listingId") WHERE status IN ('PENDING', 'PAID', 'SHIPPED', 'RELEASING', 'REFUNDING', 'DISPUTED');
